// the oshigata plates a page shows, by name: the current hashed file from scripts/build-osh.mjs
function plates(htmlText) {
  const dir = 'public/assets/osh';
  const files = existsSync(dir) ? readdirSync(dir) : [];
  return htmlText.replace(/<figure class="plate([^"]*)" aria-hidden="true">\{plate:([\w-]+)\}<\/figure>/g, (all, cls, name) => {
    const f = files.find((n) => new RegExp(`^${name}-[0-9a-f]+\\.svg$`).test(n));
    if (!f) return '';
    const svg = readFileSync(join(dir, f), 'utf8').slice(0, 400);
    const w = svg.match(/\swidth="(\d+)"/)?.[1] || 1000, h = svg.match(/\sheight="(\d+)"/)?.[1] || 300;
    return `<figure class="plate${cls}" aria-hidden="true"><img alt="" src="/assets/osh/${f}" width="${w}" height="${h}" decoding="async"></figure>`;
  });
}

const walk = (d) => (existsSync(d) ? readdirSync(d).flatMap((n) => { const p = join(d, n); return statSync(p).isDirectory() ? walk(p) : [p]; }) : []);

export function buildPages({ assets, landing = [] }) {
  const entries = [];
  for (const slug of Object.keys(PAGES)) {
    const twins = Object.fromEntries(LANGS.map((l) => [l, pathOf(l, slug)]));
    for (const lang of LANGS) {
      const r = renderCompany(slug, lang);
      const path = twins[lang];
      const crumbs = [{ name: t(lang, 'home'), path: HOME[lang] }, { name: r.copy.crumb, path }];
      const html = plates(page({
        lang, slug, path, twins, title: r.copy.title, description: r.copy.description, type: r.def.type, crumbs,
        main: r.main, kanji: r.def.kanji, gloss: r.def.gloss[lang], people: r.def.people, strings: r.strings, assets,
        mainEntity: ['AboutPage', 'ContactPage'].includes(r.def.type) ? ORG_ID : undefined,
      }));
      // Japanese: a <wbr> between phrases, so a line never breaks inside a word (scripts/pages/ja-phrases.mjs)
      const out = lang === 'ja' ? jaPhrases(html) : html;
      const file = `public${path}index.html`;
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, out);
      entries.push({ lang, path, file, slug });
    }
  }
  // the 404 page of each language folder (Cloudflare serves the nearest 404.html up the path, wrangler.json
  // not_found_handling): noindex, one sentence saying the page does not exist, and the main sections in that language.
  // The root /404.html (Uzbek) is hand-made (public/404.html).
  for (const lang of LANGS.filter((l) => l !== 'uz')) {
    const c = NOT_FOUND[lang], path = `${HOME[lang]}404.html`;
    const PRICE = { ru: '/ru/tseny/', en: '/en/prices/', ja: '/ja/prices/' }[lang];
    const to = [[HOME[lang], 'home'], [CATALOGUE_BASE[lang], 'sol'], [PRICE, 'prices'], [pathOf(lang, 'samurai'), 'ai'], [pathOf(lang, 'blog'), 'blog'], [pathOf(lang, 'about'), 'about'], [pathOf(lang, 'contact'), 'contact']];
    const main = `  <div class="pg-head">\n    <h1>${esc(c.h1)}</h1>\n    <p class="lede">${esc(c.lede)}</p>\n  </div>\n  <ul class="list nf">${to.map(([h, k]) => `<li><a class="u" href="${h}">${t(lang, k)}</a></li>`).join('')}</ul>`;
    let h = page({ lang, slug: '404', path, twins: { [lang]: path }, switchTo: HOME, title: c.title, description: c.lede, type: 'WebPage', crumbs: [], main, assets });
    // not a page of the site: no canonical, no hreflang, no og:url, no JSON-LD; noindex
    h = h.replace(/<link rel="canonical"[^>]*>\n?/, '').replace(/<link rel="alternate" hreflang="[^"]*"[^>]*>\n?/g, '').replace(/<meta property="og:url"[^>]*>\n?/, '')
      .replace(/<script type="application\/ld\+json">[\s\S]*?<\/script>\n?/, '').replace('<meta charset="utf-8">', '<meta charset="utf-8">\n<meta name="robots" content="noindex">');
    const file = `public${path}`;
    writeFileSync(file, lang === 'ja' ? jaPhrases(h) : h);
    entries.push({ lang, path, file, slug: '404', noindex: true });
  }
  // SamurAI (SOLUTIONS-SPEC §3): /samurai/ in every language, its data files, worker/gen/meta.json
  entries.push(...buildSamurai({ assets, page, t, plates, jaPhrases }));
  // the Solutions pages (SOLUTIONS-SPEC §4): catalogue, groups, solutions and the price list per language
  entries.push(...buildSolutions({ assets, page, t, plates, jaPhrases }));
  // the blog (SOLUTIONS-SPEC §5): index, posts and RSS per language; last, so its rows link the catalogue pages built above
  entries.push(...buildBlog({ assets, page, t, plates, jaPhrases, built: entries }));
  // a page that is no longer generated is removed (its URL then answers 404)
  const keep = new Set(entries.map((e) => e.file));
  for (const f of walk('public')) {
    if (!f.endsWith('/index.html') || keep.has(f) || !readFileSync(f, 'utf8').includes(MARK)) continue;
    unlinkSync(f);
    try { rmdirSync(dirname(f)); } catch { /* not empty */ }
  }

  const all = [...landing, ...entries];
  analytics(all, assets);
  writeFileSync('public/robots.txt', robots());
  writeFileSync('public/_redirects', redirects(all));
  writeFileSync('public/llms.txt', llms(all));
  if (has(site.indexnow?.key)) {
    for (const f of readdirSync('public')) if (/^[0-9a-f]{32}\.txt$/.test(f) && f !== `${site.indexnow.key}.txt`) unlinkSync(join('public', f));
    writeFileSync(`public/${site.indexnow.key}.txt`, site.indexnow.key);
  }
  writeSitemaps(all);
  console.log(`pages: ${entries.length} (${Object.keys(PAGES).join(', ')} × ${LANGS.join('/')}); sitemaps, robots.txt, llms.txt`);
  return entries;
}

// ---- robots.txt (SEO-GEO-DECISIONS: allow everything public; name the search and AI agents; close /api/ only) ----
export const AGENTS = ['Googlebot', 'Bingbot', 'YandexBot', 'Applebot', 'OAI-SearchBot', 'ChatGPT-User', 'GPTBot', 'Claude-SearchBot', 'Claude-User', 'ClaudeBot', 'PerplexityBot', 'Perplexity-User', 'Google-Extended', 'Applebot-Extended', 'meta-externalagent'];
function robots() {
  return `# qilich.com: every public page may be crawled by search engines and by AI assistants.
# Only the API is closed. The named agents get the same rules explicitly.
User-agent: *
Allow: /
Disallow: /api/

${AGENTS.map((a) => `User-agent: ${a}`).join('\n')}
Allow: /
Disallow: /api/

Sitemap: ${SITE}/sitemap.xml
`;
}

// ---- _redirects: one address per page (Guideline: Canonicals, redirects and status codes) -----------------------
// Cloudflare's asset server answers /about and /about/index.html with a 307 to /about/ (html_handling
// auto-trailing-slash), which Bing treats as temporary. These rules, matched before the asset server, make both a
// 301 to the trailing-slash URL: one static rule per page for the no-slash form (a placeholder would also match
// /robots.txt), four dynamic rules for /index.html at every depth. The query string is kept. Cloudflare allows
// 2,000 static and 100 dynamic rules; the build fails well before the static limit.
// http:// and www are not handled here: Cloudflare "Always Use HTTPS" (owner) and workers/www-redirect.
function redirects(all) {
  const paths = [...new Set(all.map((e) => e.path))].filter((p) => p !== '/' && p.endsWith('/')).sort();
  if (paths.length > 1900) throw new Error(`_redirects: ${paths.length} static rules, close to Cloudflare's 2,000 limit`);
  const depth = Math.max(...paths.map((p) => p.split('/').length - 2));
  const dyn = ['/index.html / 301'];
  for (let d = 1; d <= Math.max(depth, 3); d++) {
    const seg = Array.from({ length: d }, (_, i) => `/:p${i}`).join('');
    dyn.push(`${seg}/index.html ${seg}/ 301`);
  }
  // a catalogue page a language does not offer (the Japanese catalogue: scripts/pages/ja-market.mjs) goes to that
  // language's catalogue, so a link to it (SamurAI's results, an old bookmark) lands on a page of the same language
  const off = gone.filter((p) => !paths.includes(p)).map((p) => [p, Object.values(CATALOGUE_BASE).filter((b) => p.startsWith(b)).sort((a, b) => b.length - a.length)[0]]).filter(([, to]) => to);
  // static rules first: Cloudflare counts a static rule written after a placeholder rule as a dynamic one (limit 100)
  return `# Generated by scripts/build-pages.mjs. Every page has one address, with a trailing slash; the other forms 301 to it.
${paths.map((p) => `${p.slice(0, -1)} ${p} 301`).join('\n')}
${off.flatMap(([p, to]) => [`${p} ${to} 301`, `${p.slice(0, -1)} ${to} 301`]).join('\n')}
${dyn.join('\n')}
`;
}

// ---- llms.txt: what Qilich is and where each page is, read from the built pages -------------------------------
function llms(all) {
  const meta = (f) => {
    const h = readFileSync(f, 'utf8');
    const dec = (s) => s.replace(/&quot;/g, '"').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>');
    return { title: dec(h.match(/<title[^>]*>([^<]*)<\/title>/)?.[1] || ''), description: dec(h.match(/<meta name="description"[^>]*content="([^"]*)"/)?.[1] || '') };
  };
  const order = ['en', 'ja', 'uz', 'ru'];
  const head = { en: 'English', ja: '日本語 (for Japanese companies looking for an offshore development partner)', uz: 'Oʻzbekcha (Uzbek, the primary market)', ru: 'Русский (Russian)' };
  // a short map (SEO-GEO-DECISIONS: "ship a short one"): per language the home, the company pages, SamurAI, the
  // catalogue, its groups, the price list and the blog index; every other page is in the sitemaps
  const groups = JSON.parse(readFileSync('content/solutions.json', 'utf8')).groups.map((g) => g.id);
  const PRICE = { uz: '/narxlar/', ru: '/ru/tseny/', en: '/en/prices/', ja: '/ja/prices/' };
  const key = (lang) => new Set([HOME[lang], ...['about', 'contact', 'press', 'privacy', 'samurai', 'blog'].map((s) => pathOf(lang, s)), CATALOGUE_BASE[lang], ...groups.map((g) => `${CATALOGUE_BASE[lang]}${g}/`), PRICE[lang]]);
  const blocks = order.map((lang) => {
    const keep = key(lang);
    const mine = all.filter((e) => e.lang === lang && keep.has(e.path)).sort((a, b) => a.path.length - b.path.length || a.path.localeCompare(b.path));
    return `## ${head[lang]}\n\n${mine.map((e) => { const m = meta(e.file); return `- [${m.title}](${abs(e.path)}): ${m.description}`; }).join('\n')}`;
  });
  return `# ${site.brand}

> ${site.description.en}

${site.brand} builds iOS and Android apps, websites and web platforms, Telegram bots, backend systems and integrations, desktop apps, IoT and AI integration, for businesses in Uzbekistan and for companies in Japan that are looking for an offshore development partner. The team works in Tashkent, Uzbekistan (UTC+5), four hours behind Tokyo; five working hours overlap with the Japanese working day. ${site.brand} is new in Uzbekistan and shows no portfolio or client names.

Contact: ${site.email}, ${site.telephone}. The site is in four languages: ${LANGS.map((l) => LANG_NAME[l]).join(', ')}. Every page, including each solution and each article, is listed in ${SITE}/sitemap.xml.

${blocks.join('\n\n')}
`;
}

// ---- analytics: GA4 (consent mode) and Yandex Metrika, only when their IDs exist -------------------------------
function analytics(all, assets) {
  const ga4 = String(site.analytics.ga4 || '').trim(), ym = String(site.analytics.yandexMetrika || '').trim();
  const on = Boolean(ga4 || ym);
  for (const e of all) {
    let h = readFileSync(e.file, 'utf8');
    if (!h.includes('<!-- gen:analytics -->')) h = h.replace(/<\/body>/, '<!-- gen:analytics --><!-- /gen:analytics -->\n</body>');
    const block = on ? consentBlock(e.lang, { ga4, ym }, assets.analytics) : '';
    h = h.replace(/<!-- gen:analytics -->[\s\S]*?<!-- \/gen:analytics -->/, () => `<!-- gen:analytics -->${block}<!-- /gen:analytics -->`);
    writeFileSync(e.file, h);
  }
}
