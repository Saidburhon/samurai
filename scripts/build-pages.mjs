// Every page that is not the landing, in all four languages, plus the files that describe the whole site.
//   public/{,ru/,en/,ja/}{about,contact,privacy,press}/index.html    the company pages (scripts/pages/company.mjs)
//   public/sitemap.xml + public/sitemaps/{uz,ru,en,ja}.xml           via build-langs.mjs writeSitemaps(), every page
//   public/robots.txt                                                every crawler and AI agent admitted; /api/ closed
//   public/llms.txt                                                  a short map of the site for AI assistants
//   public/<indexnow key>.txt                                        the IndexNow key (scripts/indexnow.mjs submits)
//   <!-- gen:analytics -->                                           in every page, filled only when content/site.json
//                                                                    has a GA4 or Yandex Metrika ID (consent banner,
//                                                                    loader); empty otherwise, so nothing ships
// Called by scripts/build.mjs after build-langs, with the hashed bundles from the esbuild metafile. Returns the page
// entries ({ lang, path, file }) for the font subsets, the preloads and the sitemaps.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync, existsSync, unlinkSync, rmdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { LANGS, HOME, LANG_NAME, SITE, pathOf, abs, site, has, esc } from './site.mjs';
import { page, t } from './pages/chrome.mjs';
import { renderCompany, PAGES } from './pages/company.mjs';
import { ORG_ID } from './pages/ld.mjs';
import { writeSitemaps } from './build-langs.mjs';
import { jaPhrases } from './pages/ja-phrases.mjs';
import { buildSamurai } from './pages/samurai-build.mjs';

const MARK = '<!-- Generated by scripts/build-pages.mjs. Do not edit by hand. -->';

// the oshigata plates a page shows, by name: the current hashed file from scripts/build-osh.mjs
function plates(htmlText) {
  const dir = 'public/assets/osh';
  const files = existsSync(dir) ? readdirSync(dir) : [];
  return htmlText.replace(/<figure class="plate([^"]*)" aria-hidden="true">\{plate:([\w-]+)\}<\/figure>/g, (all, cls, name) => {
    const f = files.find((n) => new RegExp(`^${name}-[0-9a-f]+\\.svg$`).test(n));
    if (!f) return '';
    const svg = readFileSync(join(dir, f), 'utf8').slice(0, 400);
    const w = svg.match(/\swidth="(\d+)"/)?.[1] || 1000, h = svg.match(/\sheight="(\d+)"/)?.[1] || 300;
    return `<figure class="plate${cls}" aria-hidden="true"><img alt="" src="/assets/osh/${f}" width="${w}" height="${h}" decoding="async"></figure>`;
  });
}

const walk = (d) => (existsSync(d) ? readdirSync(d).flatMap((n) => { const p = join(d, n); return statSync(p).isDirectory() ? walk(p) : [p]; }) : []);

export function buildPages({ assets, landing = [] }) {
  const entries = [];
  for (const slug of Object.keys(PAGES)) {
    const twins = Object.fromEntries(LANGS.map((l) => [l, pathOf(l, slug)]));
    for (const lang of LANGS) {
      const r = renderCompany(slug, lang);
      const path = twins[lang];
      const crumbs = [{ name: t(lang, 'home'), path: HOME[lang] }, { name: r.copy.crumb, path }];
      const html = plates(page({
        lang, slug, path, twins, title: r.copy.title, description: r.copy.description, type: r.def.type, crumbs,
        main: r.main, kanji: r.def.kanji, gloss: r.def.gloss[lang], people: r.def.people, strings: r.strings, assets,
        mainEntity: ['AboutPage', 'ContactPage'].includes(r.def.type) ? ORG_ID : undefined,
      }));
      // Japanese: a <wbr> between phrases, so a line never breaks inside a word (scripts/pages/ja-phrases.mjs)
      const out = lang === 'ja' ? jaPhrases(html) : html;
      const file = `public${path}index.html`;
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, out);
      entries.push({ lang, path, file, slug });
    }
  }
  // SamurAI (SOLUTIONS-SPEC §3): /samurai/ in every language, its data files, worker/gen/meta.json
  entries.push(...buildSamurai({ assets, page, t, plates, jaPhrases }));
  // a page that is no longer generated is removed (its URL then answers 404)
  const keep = new Set(entries.map((e) => e.file));
  for (const f of walk('public')) {
    if (!f.endsWith('/index.html') || keep.has(f) || !readFileSync(f, 'utf8').includes(MARK)) continue;
    unlinkSync(f);
    try { rmdirSync(dirname(f)); } catch { /* not empty */ }
  }

  const all = [...landing, ...entries];
  analytics(all, assets);
  writeFileSync('public/robots.txt', robots());
  writeFileSync('public/llms.txt', llms(all));
  if (has(site.indexnow?.key)) {
    for (const f of readdirSync('public')) if (/^[0-9a-f]{32}\.txt$/.test(f) && f !== `${site.indexnow.key}.txt`) unlinkSync(join('public', f));
    writeFileSync(`public/${site.indexnow.key}.txt`, site.indexnow.key);
  }
  writeSitemaps(all);
  console.log(`pages: ${entries.length} (${Object.keys(PAGES).join(', ')} × ${LANGS.join('/')}); sitemaps, robots.txt, llms.txt`);
  return entries;
}

// ---- robots.txt (SEO-GEO-DECISIONS: allow everything public; name the search and AI agents; close /api/ only) ----
export const AGENTS = ['Googlebot', 'Bingbot', 'YandexBot', 'Applebot', 'OAI-SearchBot', 'ChatGPT-User', 'GPTBot', 'Claude-SearchBot', 'Claude-User', 'ClaudeBot', 'PerplexityBot', 'Perplexity-User', 'Google-Extended', 'Applebot-Extended', 'meta-externalagent'];
function robots() {
  return `# qilich.com: every public page may be crawled by search engines and by AI assistants.
# Only the API is closed. The named agents get the same rules explicitly.
User-agent: *
Allow: /
Disallow: /api/

${AGENTS.map((a) => `User-agent: ${a}`).join('\n')}
Allow: /
Disallow: /api/

Sitemap: ${SITE}/sitemap.xml
`;
}

// ---- llms.txt: what Qilich is and where each page is, read from the built pages -------------------------------
function llms(all) {
  const meta = (f) => {
    const h = readFileSync(f, 'utf8');
    const dec = (s) => s.replace(/&quot;/g, '"').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>');
    return { title: dec(h.match(/<title[^>]*>([^<]*)<\/title>/)?.[1] || ''), description: dec(h.match(/<meta name="description"[^>]*content="([^"]*)"/)?.[1] || '') };
  };
  const order = ['en', 'ja', 'uz', 'ru'];
  const head = { en: 'English', ja: '日本語 (for Japanese companies looking for an offshore development partner)', uz: 'Oʻzbekcha (Uzbek, the primary market)', ru: 'Русский (Russian)' };
  const blocks = order.map((lang) => {
    const mine = all.filter((e) => e.lang === lang).sort((a, b) => a.path.length - b.path.length || a.path.localeCompare(b.path));
    return `## ${head[lang]}\n\n${mine.map((e) => { const m = meta(e.file); return `- [${m.title}](${abs(e.path)}): ${m.description}`; }).join('\n')}`;
  });
  return `# ${site.brand}

> ${site.description.en}

${site.brand} builds iOS and Android apps, websites and web platforms, Telegram bots, backend systems and integrations, desktop apps, IoT and AI integration, for businesses in Uzbekistan and for companies in Japan that are looking for an offshore development partner. The team works in Tashkent, Uzbekistan (UTC+5), four hours behind Tokyo; five working hours overlap with the Japanese working day. ${site.brand} is new in Uzbekistan and shows no portfolio or client names.

Contact: ${site.email}, ${site.telephone}. The site is in four languages: ${LANGS.map((l) => LANG_NAME[l]).join(', ')}.

${blocks.join('\n\n')}
`;
}

// ---- analytics: GA4 (consent mode) and Yandex Metrika, only when their IDs exist -------------------------------
function analytics(all, assets) {
  const ga4 = String(site.analytics.ga4 || '').trim(), ym = String(site.analytics.yandexMetrika || '').trim();
  const on = Boolean(ga4 || ym);
  for (const e of all) {
    let h = readFileSync(e.file, 'utf8');
    if (!h.includes('<!-- gen:analytics -->')) h = h.replace(/<\/body>/, '<!-- gen:analytics --><!-- /gen:analytics -->\n</body>');
    const block = on ? consentBlock(e.lang, { ga4, ym }, assets.analytics) : '';
    h = h.replace(/<!-- gen:analytics -->[\s\S]*?<!-- \/gen:analytics -->/, () => `<!-- gen:analytics -->${block}<!-- /gen:analytics -->`);
    writeFileSync(e.file, h);
  }
}
// the banner never covers content on load and never moves the layout: it is fixed, appears only after the visitor
// has scrolled (or after a few seconds on a page that cannot scroll), and the page end is padded while it shows
function consentBlock(lang, ids, src) {
  const L = (k) => t(lang, k);
  const cfg = JSON.stringify({ ga4: ids.ga4 || null, ym: ids.ym || null }).replace(/</g, '\\u003c');
  return `
<script type="application/json" id="qilich-analytics">${cfg}</script>
<style>.consent{position:fixed;z-index:40;left:var(--m,20px);right:var(--m,20px);bottom:16px;max-width:560px;margin-left:auto;display:flex;flex-wrap:wrap;align-items:center;gap:10px 16px;padding:14px 16px;background:#ECE6DA;color:#0F0E0C;box-shadow:0 0 0 1px rgba(15,14,12,.22);font:400 14px/1.4 var(--sans,sans-serif);transform:translateY(calc(100% + 24px));transition:transform .45s cubic-bezier(.35,0,0,1)}.consent.on{transform:none}.consent[hidden]{display:none}.consent p{flex:1 1 260px;margin:0}.consent a{border-bottom:1px solid rgba(15,14,12,.35)}.consent button{height:36px;padding:0 14px;border:1px solid #0F0E0C;background:none;color:inherit;font:inherit;font-size:13px;letter-spacing:.06em;cursor:pointer}.consent button[data-consent=granted]{background:#0F0E0C;color:#ECE6DA}html.consent-pad body{padding-bottom:var(--consent-h,0px)}@media (min-width:861px){.consent{bottom:56px}}@media (prefers-reduced-motion:reduce){.consent{transition:none}}</style>
<div class="consent" id="consent" role="region" aria-label="${esc(L('ckLabel'))}" hidden><p>${L('ckText')} <a href="${pathOf(lang, 'privacy')}">${L('ckMore')}</a></p><button type="button" data-consent="granted">${L('ckYes')}</button><button type="button" data-consent="denied">${L('ckNo')}</button></div>
<script type="module" src="${src}"></script>
`;
}
