// Every drawing on the site, from the one generator (src/sword/drawing.js) and the dial (src/sword/dial.js):
//   - the inline drawings (hero, B7 plan, bookend saya) and their HTML labels  -> public/index.html  <!-- gen:osh -->
//   - the dial                                                                 -> public/index.html  <!-- gen:dial -->
//   - the CSS that places the hero drawing with no JS                          -> src/styles/gen/osh.css
//   - the flow-mode plates (no <text>: their labels are HTML beside them)      -> public/assets/osh/<name>-<hash>.svg
//     every <img data-osh="name"> in public/index.html and public/404.html gets the hashed src, width and height
import { readFileSync, writeFileSync, mkdirSync, readdirSync, unlinkSync } from 'node:fs';
import { createHash } from 'node:crypto';
import * as D from '../src/sword/drawing.js';
import { dial } from '../src/sword/dial.js';
import * as G from '../src/sword/geom-core.js';

const holes = JSON.parse(readFileSync('src/sword/girih-holes.json', 'utf8')).holes;
const OUT = 'public/assets/osh';
const hash = (s) => createHash('sha256').update(s).digest('hex').slice(0, 10);
const pct = (v) => +(v * 100).toFixed(3);

// ---------------- inline drawings ----------------
const hero = D.hero(holes);
const plan = D.plan();
const saya = D.sayaDrawing();
const heroPlate = D.plateSvg(hero.parts, { pad: 34 }); // only for its viewBox
const vb = heroPlate.svg.match(/viewBox="([^"]+)"/)[1].split(' ').map(Number);
const [vx, vy, vw, vh] = vb;
const label = (l) => {
  const x = pct((l.at[0] - vx) / vw), y = pct((l.at[1] - vy) / vh);
  const rot = l.rot === 'screen' ? 'calc(-1 * var(--osh-rot))' : `${(+l.rot).toFixed(2)}deg`;
  return `<span class="ol${l.cls ? ' ' + l.cls : ''}${l.anchor === 'middle' ? ' mid' : ''}" style="--x:${x}%;--y:${y}%;--r:${rot}">${l.html}</span>`;
};
const osh = `<svg id="osh" viewBox="${vb.join(' ')}" aria-hidden="true"><g id="osh-hero" fill="none" stroke="currentColor" stroke-linecap="round" stroke-linejoin="round">${hero.parts.join('')}</g>` +
  `<g id="osh-plan" class="shiro" fill="none" stroke="currentColor" stroke-linecap="round" stroke-linejoin="round" hidden>${plan.parts.join('')}</g>` +
  `<g id="osh-saya" fill="none" stroke="currentColor" stroke-linecap="round" stroke-linejoin="round" hidden>${saya.parts.join('')}</g></svg>` +
  `<div class="osh-labels">${hero.labels.map(label).join('')}</div>`;

// ---------------- placement CSS (§2.1): the drawing's axis from K to T lies on the layout's anchors ----------------
const ox = pct(-vx / vw), oy = pct(-vy / vh);
const wK = (vw / hero.LKT).toFixed(5);
const A = D.ANCHORS;
const place = (a, fallbackDeg, fallbackW) => {
  const dx = ((a.T[0] - a.K[0]) * 100).toFixed(2), dy = ((a.T[1] - a.K[1]) * 100).toFixed(2);
  return {
    main: `left:${(a.K[0] * 100).toFixed(2)}vw;top:calc(var(--sh) * ${a.K[1]});--osh-rot:atan2(calc(var(--sh) * ${(dy / 100).toFixed(4)}), ${dx}vw);width:calc(hypot(${dx}vw, calc(var(--sh) * ${(dy / 100).toFixed(4)})) * ${wK})`,
    fb: `--osh-rot:${fallbackDeg}deg;width:calc(${fallbackW}vw * ${wK})`,
  };
};
const L = place(A.land, -18, 87), Pt = place(A.port, -82.5, 72);
mkdirSync('src/styles/gen', { recursive: true });
// the hamon underline for links: the real temper line of the blade, drawn left to right on hover
const hw = [];
for (let i = 0; i <= 72; i++) { const u = 0.04 + 0.9 * i / 72; hw.push([(i * 400 / 72).toFixed(1), (3 + (0.72 - G.hamonV(u)) * 34).toFixed(2)]); }
const hamonPath = 'M' + hw.map((p) => p.join(' ')).join('L');
const hamonUri = (c) => `url("data:image/svg+xml,${encodeURIComponent(`<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 400 6' preserveAspectRatio='none'><path d='${hamonPath}' fill='none' stroke='${c}' stroke-width='1' vector-effect='non-scaling-stroke'/></svg>`)}")`;
writeFileSync('src/styles/gen/hamon.css', `/* generated by scripts/build-osh.mjs: the hamon underline of links */\n:root{--hamon-k:${hamonUri('#0F0E0C')};--hamon-w:${hamonUri('#ECE6DA')}}\n`);
const css = `/* generated by scripts/build-osh.mjs: the hero drawing placed with no JS (§2.1) and the stroke classes */
#osh-paper{position:absolute;aspect-ratio:${vw}/${vh};transform-origin:${ox}% ${oy}%;translate:-${ox}% -${oy}%;rotate:var(--osh-rot);${L.main}}
#osh-paper .p-only{display:none}
@media (aspect-ratio < 1.2){#osh-paper{${Pt.main}}#osh-paper .l-only{display:none}#osh-paper .p-only{display:block}}
@supports not (width:hypot(1px,1px)){#osh-paper{${L.fb}}@media (aspect-ratio < 1.2){#osh-paper{${Pt.fb}}}}
${D.strokeCss('currentColor', '#osh ')}
`;
writeFileSync('src/styles/gen/osh.css', css);

// ---------------- plates ----------------
mkdirSync(OUT, { recursive: true });
const plates = {
  kissaki: D.plateKissaki(), utsuri: D.plateUtsuri(),
  'yaki-1': D.plateYaki(1), 'yaki-2': D.plateYaki(2), 'yaki-3': D.plateYaki(3), 'yaki-4': D.plateYaki(4),
  togi: D.plateTogi(), tsuba: D.plateTsuba(holes), noto: D.plateNoto(), broken: D.plateBroken(),
};
const files = {};
for (const [name, p] of Object.entries(plates)) {
  const f = `${name}-${hash(p.svg)}.svg`;
  writeFileSync(`${OUT}/${f}`, p.svg);
  files[name] = { src: `/assets/osh/${f}`, width: p.width, height: p.height, bytes: p.svg.length };
}
for (const f of readdirSync(OUT)) if (!Object.values(files).some((v) => v.src.endsWith('/' + f))) unlinkSync(`${OUT}/${f}`);

// ---------------- write into the pages ----------------
const dialSvg = dial(holes);
function inject(file) {
  let html = readFileSync(file, 'utf8');
  html = html.replace(/<!-- gen:osh -->[\s\S]*?<!-- \/gen:osh -->/, `<!-- gen:osh -->${osh}<!-- /gen:osh -->`);
  html = html.replace(/<!-- gen:dial -->[\s\S]*?<!-- \/gen:dial -->/, `<!-- gen:dial -->${dialSvg}<!-- /gen:dial -->`);
  html = html.replace(/<img([^>]*?) data-osh="([\w-]+)"([^>]*?)>/g, (all, a, name, b) => {
    const p = files[name]; if (!p) throw new Error(`${file}: no plate named ${name}`);
    const attrs = (a + b).replace(/\s(src|width|height)="[^"]*"/g, '');
    return `<img${attrs.replace(/\s+$/, '')} data-osh="${name}" src="${p.src}" width="${p.width}" height="${p.height}">`;
  });
  writeFileSync(file, html);
}
inject('public/index.html');
inject('public/404.html');
const kb = (n) => (n / 1024).toFixed(1) + ' KB';
console.log(`osh: inline ${kb(osh.length)} (hero ${kb(hero.parts.join('').length)}, plan ${kb(plan.parts.join('').length)}, saya ${kb(saya.parts.join('').length)}), dial ${kb(dialSvg.length)}; plates ${Object.entries(files).map(([k, v]) => `${k} ${kb(v.bytes)}`).join(', ')}`);
