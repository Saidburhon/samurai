export function drawIcon(ctx, name, x, y, cell, color) {
  const rows = ICONS[name];
  ctx.fillStyle = color;
  for (let r = 0; r < 13; r++)
    for (let c = 0; c < 13; c++)
      if (rows[r][c] === '#') ctx.fillRect(x + c * cell, y + r * cell, cell, cell);
}
